def translate(key: str, language: str = "en", **params) -> str:
    """
    Translate a key to the specified language.
    
    Args:
        key: Translation key
        language: Language code (default: "en")
        **params: Parameters to substitute in the translation string
        
    Returns:
        Translated string with parameters substituted
    """
    lang = language.lower() if language else "en"
    translations = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    template = translations.get(key, TRANSLATIONS["en"].get(key, key))
    
    # Substitute parameters
    try:
        return template.format(**params)
    except KeyError:
        # If parameter substitution fails, return template as-is
        return template





